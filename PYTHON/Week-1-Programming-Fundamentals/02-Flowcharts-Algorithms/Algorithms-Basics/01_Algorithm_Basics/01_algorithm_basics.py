# ------------------------------------------------------------
# 1. What Is an Algorithm?
# ------------------------------------------------------------

# An algorithm is a finite sequence of clear steps used to
# solve a problem or complete a task.

# Example: Algorithm to display a message
#
# Step 1: Start
# Step 2: Display "Hello, Python!"
# Step 3: Stop

print("Hello, Python!")


# ------------------------------------------------------------
# 2. Algorithm to Add Two Numbers
# ------------------------------------------------------------

# Problem:
# Find the sum of two numbers.
#
# Algorithm:
# Step 1: Start
# Step 2: Input the first number
# Step 3: Input the second number
# Step 4: Add both numbers
# Step 5: Display the sum
# Step 6: Stop

first_number = int(input("Enter the first number: "))
second_number = int(input("Enter the second number: "))

# Perform the calculation
total = first_number + second_number

# Display the result
print("First number:", first_number)
print("Second number:", second_number)
print("Sum:", total)


# ------------------------------------------------------------
# 3. Algorithm to Calculate the Average of Two Numbers
# ------------------------------------------------------------

# Problem:
# Calculate the average of two numbers.
#
# Algorithm:
# Step 1: Start
# Step 2: Input two numbers
# Step 3: Add the numbers
# Step 4: Divide the sum by 2
# Step 5: Display the average
# Step 6: Stop

# Example values
number1 = 10
number2 = 20

average = (number1 + number2) / 2

print("Number 1:", number1)
print("Number 2:", number2)
print("Average:", average)


# ------------------------------------------------------------
# 4. Input - Process - Output
# ------------------------------------------------------------

# Most basic problem-solving algorithms can be understood as:
#
# Input   -> Information required to solve the problem
# Process -> Operations performed on the input
# Output  -> Final result

# Example:
# Input   : 5 and 3
# Process : 5 + 3
# Output  : 8

a = 5
b = 3

result = a + b

print("Input:", a, "and", b)
print("Process: Addition")
print("Output:", result)


