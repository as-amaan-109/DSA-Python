product = number1 * number2

print("Input:", number1, "and", number2)
print("Process: Multiplication")
print("Output:", product)


# ------------------------------------------------------------
# 7. Algorithm Dry Run
# ------------------------------------------------------------

# A dry run means manually tracing an algorithm using sample values.
#
# Algorithm:
# Step 1: A = 5
# Step 2: B = 3
# Step 3: SUM = A + B
# Step 4: Display SUM
#
# Dry run:
# A = 5
# B = 3
# SUM = 5 + 3 = 8

print("\n--- Algorithm Dry Run ---")

a = 5
b = 3
sum_result = a + b

print("A:", a)
print("B:", b)
print("SUM:", sum_result)


