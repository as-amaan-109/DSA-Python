# ------------------------------------------------------------
# 1. Basic Structure of an Algorithm
# ------------------------------------------------------------

# Problem: Display a welcome message.
#
# Algorithm:
# Step 1: Start.
# Step 2: Display "Welcome to Python".
# Step 3: Stop.

print("Welcome to Python")


# ------------------------------------------------------------
# 2. Algorithm to Add Two Numbers
# ------------------------------------------------------------

# Problem: Calculate the sum of two numbers.
#
# Algorithm:
# Step 1: Start.
# Step 2: Input the first number.
# Step 3: Input the second number.
# Step 4: Calculate SUM = first number + second number.
# Step 5: Display SUM.
# Step 6: Stop.

print("\n--- Addition of Two Numbers ---")

first_number = int(input("Enter the first number: "))
second_number = int(input("Enter the second number: "))

total = first_number + second_number

print("First number:", first_number)
print("Second number:", second_number)
print("Sum:", total)


# ------------------------------------------------------------
# 3. Algorithm to Calculate the Area of a Rectangle
# ------------------------------------------------------------

# Problem: Calculate the area of a rectangle.
#
# Formula:
# Area = Length * Breadth
#
# Algorithm:
# Step 1: Start.
# Step 2: Take the length.
# Step 3: Take the breadth.
# Step 4: Calculate AREA = length * breadth.
# Step 5: Display AREA.
# Step 6: Stop.

print("\n--- Area of a Rectangle ---")

length = 5
breadth = 3

area = length * breadth

print("Length:", length)
print("Breadth:", breadth)
print("Area:", area)


# ------------------------------------------------------------
# 4. Algorithm to Calculate the Average of Three Numbers
# ------------------------------------------------------------

# Problem: Find the average of three numbers.
#
# Formula:
# Average = (A + B + C) / 3
#
# Algorithm:
# Step 1: Start.
# Step 2: Take three numbers A, B, and C.
# Step 3: Calculate TOTAL = A + B + C.
# Step 4: Calculate AVERAGE = TOTAL / 3.
# Step 5: Display AVERAGE.
# Step 6: Stop.

print("\n--- Average of Three Numbers ---")

a = 10
b = 20
c = 30

total_numbers = a + b + c
average = total_numbers / 3

print("Numbers:", a, b, c)
print("Total:", total_numbers)
print("Average:", average)


# ------------------------------------------------------------
# 5. Algorithm to Convert Celsius into Fahrenheit
# ------------------------------------------------------------

# Problem: Convert a temperature from Celsius to Fahrenheit.
#
# Formula:
# Fahrenheit = (Celsius * 9 / 5) + 32
#
# Algorithm:
# Step 1: Start.
# Step 2: Take temperature in Celsius.
# Step 3: Apply the conversion formula.
# Step 4: Display the temperature in Fahrenheit.
# Step 5: Stop.

print("\n--- Celsius to Fahrenheit ---")

celsius = 25

fahrenheit = (celsius * 9 / 5) + 32

print("Temperature in Celsius:", celsius)
print("Temperature in Fahrenheit:", fahrenheit)


# ------------------------------------------------------------
# 6. Understanding Input, Process, and Output
# ------------------------------------------------------------

# Example:
# Input   : 8 and 4
# Process : 8 * 4
# Output  : 32

print("\n--- Input, Process, and Output ---")

